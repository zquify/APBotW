def _load_state():
    try:
        with STATE_FILE.open("r", encoding="utf-8") as f:
            state = json.load(f)
    except FileNotFoundError:
        state = {}

    if not isinstance(state, dict):
        raise DeliveryError("Delivery state file is not a JSON object")

    return state


def _save_state(state):
    STATE_FILE.parent.mkdir(parents=True, exist_ok=True)
    temporary = STATE_FILE.with_suffix(".tmp")

    with temporary.open("w", encoding="utf-8") as f:
        json.dump(state, f, indent=2)
        f.write("\n")

    temporary.replace(STATE_FILE)


class APItemDelivery:
    """Deliver newly received NetworkItems in their original AP order."""

    def __init__(self, slot_key):
        # Use a stable identifier for this AP server + slot.
        self.slot_key = slot_key
        self.state = _load_state()
        self.progress = self.state.setdefault(
            slot_key, {"next_index": 0}
        )

    @property
    def next_index(self):
        return int(self.progress.get("next_index", 0))

    def process(self, items_received, get_item_name):
        """Process items from next_index onward.

        items_received: ctx.items_received
        get_item_name: callable taking a NetworkItem and returning its name

        Stops on an unmapped item or a bridge error. Later items are not
        delivered out of order.
        """
        while self.next_index < len(items_received):
            index = self.next_index
            network_item = items_received[index]
            item_name = get_item_name(network_item)

            if item_name == "__Victory__":
                self._advance()
                continue

            tower_number = TOWER_MAP.get(item_name)

            if tower_number is not None:
                try:
                    send_tower_to_bridge(tower_number)
                except DeliveryError:
                    log.exception(
                        "Failed to activate tower %r at index %d; "
                        "delivery paused.",
                        item_name, index,
                    )
                    return False

                self._advance()
                log.info(
                    "Activated AP tower %d: %s",
                    tower_number,
                    item_name,
                )
                continue

            if item_name == "Paraglider":
                try:
                    send_paraglider_to_bridge()
                except DeliveryError:
                    log.exception(
                        "Failed to unlock Paraglider at index %d; "
                        "delivery paused.",
                        index,
                    )
                    return False

                self._advance()
                log.info(
                    "Unlocked AP Paraglider"
                )
                continue

            if item_name == "Heart Container":
                try:
                    upgraded = send_heart_container_to_bridge()
                except DeliveryError:
                    log.exception(
                        "Failed to increase max health for Heart Container "
                        "at index %d; delivery paused.",
                        index,
                    )
                    return False

                self._advance()
                if upgraded:
                    log.info("Increased max health for AP Heart Container")
                else:
                    log.info(
                        "AP max health already at maximum; "
                        "Heart Container consumed."
                    )
                continue

            if item_name == "Stamina Vessel":
                try:
                    upgraded = send_stamina_vessel_to_bridge()
                except DeliveryError:
                    log.exception(
                        "Failed to increase max stamina for Stamina Vessel "
                        "at index %d; delivery paused.",
                        index,
                    )
                    return False

                self._advance()
                if upgraded:
                    log.info("Increased max stamina for AP Stamina Vessel")
                else:
                    log.info(
                        "AP max stamina already at maximum; "
                        "Stamina Vessel consumed."
                    )
                continue

            rupee_amount = _rupee_amount_from_item(item_name)
            if rupee_amount is not None:
                try:
                    send_rupees_to_bridge(rupee_amount)
                except DeliveryError:
                    log.exception(
                        "Failed to grant %d rupees at index %d; "
                        "delivery paused.",
                        rupee_amount, index,
                    )
                    return False

                self._advance()
                log.info("Granted %d AP rupees", rupee_amount)
                continue

            inventory_slot = {
                "Weapon Slot": "WEAPON",
                "Bow Slot": "BOW",
                "Shield Slot": "SHIELD",
            }.get(item_name)
            if inventory_slot is not None:
                try:
                    upgraded = send_inventory_slot_to_bridge(inventory_slot)
                except DeliveryError:
                    log.exception(
                        "Failed to increase %s capacity at index %d; "
                        "delivery paused.",
                        inventory_slot.lower(), index,
                    )
                    return False

                self._advance()
                if upgraded:
                    log.info(
                        "Increased AP %s capacity",
                        inventory_slot.lower(),
                    )
                else:
                    log.info(
                        "AP %s capacity already at maximum; "
                        "slot item consumed.",
                        inventory_slot.lower(),
                    )
                continue
            
            mapping = ITEM_MAP.get(item_name)
            if mapping is None:
                # Temporary behavior for the physical-item delivery test.
                # Preserve unsupported items for implementation later.
                deferred = self.progress.setdefault("deferred_items", [])
                deferred.append({
                    "index": index,
                    "name": item_name,
                })
                self._advance()

                log.warning(
                    "Deferred unsupported AP item %r at index %d; "
                    "continuing so physical-item delivery can be tested.",
                    item_name, index,
                )
                continue

            actor_name, quantity = mapping

            try:
                send_to_bridge(actor_name, quantity)
            except DeliveryError:
                log.exception(
                    "Failed to deliver AP item %r at index %d; "
                    "delivery paused.",
                    item_name, index,
                )
                return False

            # Advance only after receiving an OK from the bridge.
            self._advance()
            log.info(
                "Delivered AP item %d: %s -> %s x%d",
                index, item_name, actor_name, quantity,
            )

        return True

    def _advance(self):
        self.progress["next_index"] = self.next_index + 1
        _save_state(self.state)